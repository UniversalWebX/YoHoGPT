import random

import numpy as np

from yohogpt.data.dedup import Decontaminator, ExactDeduper, MinHashDeduper
from yohogpt.data.fim import fim_transform
from yohogpt.data.filters import detect_license, quality_reject_reason, redact
from yohogpt.data.sft_formats import to_messages, to_preference
from yohogpt.data.sources import load_catalogue


def test_catalogue_loads_and_weights_normalise():
    cat = load_catalogue()
    for stage in ("pretrain", "sft", "dpo"):
        w = cat.mixture_weights(stage)
        assert w and abs(sum(w.values()) - 1) < 1e-9
    assert "mit" in cat.license_allowlist and cat.eval_sets


def test_redaction():
    text = 'key = "AKIAABCDEFGHIJKLMNOP"\npassword = "hunter2hunter2"\nmail me: bob@corp.io\nhost 52.14.1.9'
    out = redact(text)
    assert "AKIA" not in out and "hunter2" not in out and "bob@corp.io" not in out and "52.14.1.9" not in out


def test_quality_filters():
    assert quality_reject_reason("x") == "too_short"
    assert quality_reject_reason("# auto-generated, do not edit\n" + "a = 1\n" * 20, "python") == "autogenerated"
    assert quality_reject_reason("def f():\n    return 1\n" * 10, "python") is None
    assert quality_reject_reason("a" * 2000, "python") == "long_line"


def test_license_detection():
    assert detect_license("Permission is hereby granted, free of charge, to any person") == "mit"
    assert detect_license("Apache License\nVersion 2.0, January 2004") == "apache-2.0"
    assert detect_license("GNU General Public License v3") == "gpl"


def test_dedup():
    ex = ExactDeduper()
    assert not ex.is_duplicate("a = 1\n")
    assert ex.is_duplicate("a = 1   \n")  # trailing whitespace normalised
    base = " ".join(f"token{i}" for i in range(300))
    near = MinHashDeduper()
    assert not near.is_duplicate(base)
    assert near.is_duplicate(base.replace("token150", "changed"))
    assert not near.is_duplicate(" ".join(f"other{i}" for i in range(300)))


def test_decontamination():
    d = Decontaminator(["def has_close_elements(numbers, threshold): check if in given list of numbers are any two"], ngram=8)
    assert d.is_contaminated("x\ndef has_close_elements(numbers, threshold): check if in given list of numbers")
    assert not d.is_contaminated("def totally_unrelated(): return 1")


def test_fim_preserves_content():
    rng = random.Random(0)
    text = "def f(x):\n    return x * 2\n"
    outs = [fim_transform(text, rng, fim_rate=1.0) for _ in range(20)]
    for o in outs:
        assert "<|fim_middle|>" in o
        stripped = o
        for t in ("<|fim_prefix|>", "<|fim_suffix|>", "<|fim_middle|>"):
            stripped = stripped.replace(t, "")
        assert sorted(stripped) == sorted(text)


def test_sft_formats():
    m = to_messages({"q": "Write hello world", "a": "print('hi')"}, "instruction_response",
                    {"instruction": "q", "response": "a"})
    assert [x["role"] for x in m] == ["system", "user", "assistant"]
    m = to_messages({"text": "<|im_start|>user\nhi<|im_end|>\n<|im_start|>assistant\nhello<|im_end|>"}, "chatml_text")
    assert m[-1] == {"role": "assistant", "content": "hello"}
    m = to_messages({"conversations": [{"from": "human", "value": "a"}, {"from": "gpt", "value": "b"}]}, "sharegpt")
    assert m[-1]["content"] == "b"
    p = to_preference({"chosen": [{"role": "user", "content": "q"}, {"role": "assistant", "content": "good"}],
                       "rejected": [{"role": "user", "content": "q"}, {"role": "assistant", "content": "bad"}]})
    assert p["chosen"] == "good" and p["rejected"] == "bad"


def test_prepare_and_mixture(tmp_path, raw_corpus, tokenizer_dir):
    from yohogpt.data.dataset import MixtureSampler, PackedTokens
    from yohogpt.data.prepare import prepare

    meta = prepare(raw_corpus, tmp_path / "proc", str(tokenizer_dir / "tokenizer.json"), fim_rate=0.5, workers=1)
    assert meta["tokens"] > 1000 and meta["stats"]["kept"] > 200
    pt = PackedTokens(tmp_path / "proc")
    s = MixtureSampler({"a": (pt, 1.0)}, seq_len=32, batch_size=4, seed=0)
    x, y = s.batch(0)
    assert x.shape == (4, 32) and torch_equal(x[:, 1:], y[:, :-1])
    x2, _ = s.batch(0)
    assert torch_equal(x, x2)  # deterministic
    assert int(x.max()) < meta["vocab_size"]


def torch_equal(a, b):
    return bool((a == b).all())


def test_sft_dataset_masks(tmp_path, tokenizer):
    import json

    from yohogpt.data.dataset import SFTDataset

    f = tmp_path / "sft.jsonl"
    rows = [{"messages": [{"role": "user", "content": f"q{i}"}, {"role": "assistant", "content": f"answer {i}"}]}
            for i in range(30)]
    f.write_text("\n".join(json.dumps(r) for r in rows))
    ds = SFTDataset([str(f)], tokenizer, seq_len=64)
    x, y = ds.batch(np.random.default_rng(0), 2)
    assert x.shape == y.shape == (2, 64)
    assert (y != -100).any() and (y == -100).any()
